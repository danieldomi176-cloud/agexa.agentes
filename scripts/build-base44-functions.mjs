/** Produce standalone editor artifacts without installing SDKs or contacting Base44. */
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const check = process.argv.includes('--check');
for (const name of ['agexaConversionFeed', 'publishConversionEvent']) {
  const result = await build({
    entryPoints: [`integrations/base44/${name}.ts`],
    bundle: true,
    write: false,
    platform: 'neutral',
    format: 'esm',
    target: 'es2022',
    external: ['npm:@base44/sdk@0.8.57'],
    legalComments: 'none',
    banner: {
      js: '// GENERATED by npm run base44:bundle. Not deployed or Deno-runtime validated.',
    },
  });
  const path = `integrations/base44/deploy/${name}.ts`;
  const text = result.outputFiles[0].text;
  if (check) {
    if ((await readFile(path, 'utf8')) !== text) throw Error(`Stale artifact: ${path}`);
  } else {
    await mkdir('integrations/base44/deploy', { recursive: true });
    await writeFile(path, text);
  }
}
console.log(
  check
    ? 'Base44 artifacts match sources (no deploy).'
    : 'Base44 editor artifacts generated (no deploy).',
);
